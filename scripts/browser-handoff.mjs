  await mutate({ action: 'addSession', shelfId, revision: 2, sessionId: fixture.secondSessionId });
  await page.getByRole('button', { name: '任务资料夹', exact: true }).click();
  await page.getByRole('combobox', { name: '工作区', exact: true }).selectOption(fixture.workspaceId);
  await page.locator('.ts-card').filter({ hasText: title }).click();
  const sourceWorkspace = page.locator(`.ts-handoff-workspace[data-workspace-id="${fixture.workspaceId}"]`);
  const firstSource = sourceWorkspace.getByRole('checkbox', { name: '任务资料夹 · 合成讨论', exact: true });
  const secondSource = sourceWorkspace.getByRole('checkbox', { name: '任务资料夹 · 合成部署讨论', exact: true });
  await firstSource.check(); await secondSource.check();
  await page.getByRole('button', { name: '生成交接包', exact: true }).click();
  const editor = page.getByLabel('交接包预览与编辑', { exact: true }); await editor.waitFor();
  const original = await editor.inputValue();
  const readable = page.getByLabel('易读版预览与编辑', { exact: true }); await readable.waitFor();
  const humanOriginal = await readable.inputValue();
  assert.match(humanOriginal, /下一步/); assert.match(humanOriginal, /你说/);
  assert.ok(!humanOriginal.includes(fixture.sessionId)); assert.match(humanOriginal, /第二段合成讨论/);
  const leftBox = await editor.boundingBox(), rightBox = await readable.boundingBox();
  assert.ok(rightBox.x > leftBox.x + leftBox.width, 'raw must be left of readable');
  check('Two versions share source content; readable omits technical IDs and appears on the right');
  assert.match(original, /这是一条本地合成会话/); assert.match(original, /第二段合成讨论/);
  assert.match(original, /讨论 2/); assert.match(original, /事件/); assert.ok(original.includes(fixture.sessionId));
  check('Two persisted sessions produce cited excerpts without a model call');
  const edited = `${original}\n\n人工补充：确认只在本地部署。`;
  await editor.fill(edited);
  await page.getByLabel('交接输出版本', { exact: true }).selectOption('raw');
  await page.getByRole('button', { name: '复制交接包', exact: true }).click();
  await page.getByText('已复制原始记录，可粘贴到目标会话。', { exact: true }).waitFor();
  assert.equal((await page.evaluate(() => navigator.clipboard.readText())).replaceAll('\r\n', '\n'), edited);
  const downloading = page.waitForEvent('download'); await page.getByRole('button', { name: '下载交接包', exact: true }).click();
  assert.equal(await readFile(await (await downloading).path(), 'utf8'), edited);
  check('Edited handoff copies and downloads exactly');
  const humanEdited = `${humanOriginal}\n\n人工补充：确认只在本地部署。`;
  await readable.fill(humanEdited);
  await page.getByRole('button', { name: '易读版', exact: true }).click();
  assert.equal(await editor.count(), 0); assert.equal(await readable.inputValue(), humanEdited);
  await page.getByRole('button', { name: '原始记录', exact: true }).click();
